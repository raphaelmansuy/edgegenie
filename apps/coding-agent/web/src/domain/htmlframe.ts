/** `displayHTML` output, drawn in a sandboxed frame. Pure: the document and the height protocol.
 *
 * HTML a notebook produces is code that someone else wrote (or a library did), so it never touches the
 * app's own page. It is the `srcdoc` of an iframe with `sandbox="allow-scripts"` and nothing else: no
 * same-origin, so it cannot read the app's cookies, storage or DOM, and cannot call `/api` as the user.
 * Scripts do run, because a styled table, a plotly chart or a widget needs them.
 *
 * The one thing the sandbox takes away is the ability to measure the content from outside, so the
 * document measures itself and posts its height to the parent, which accepts the message only from that
 * frame and only as a number within bounds.
 */

export const MIN_FRAME = 24;
export const MAX_FRAME = 640;

/** The attribute value. Scripts and popups (for links); never `allow-same-origin`. */
export const FRAME_SANDBOX = "allow-scripts allow-popups allow-popups-to-escape-sandbox";

/** The full document for a frame, with a script that reports its height under `id`. */
export function frameDoc(html: string, id: string): string {
  // `id` is generated by the app (never from the cell), but it is still encoded as a JSON string so no
  // character in it can end the script.
  const key = JSON.stringify(String(id)).replace(/</g, "\\u003c");
  const report = `<script>(function(){var k=${key};function s(){var h=Math.ceil(Math.max(` +
    `document.documentElement.scrollHeight,document.body?document.body.scrollHeight:0));` +
    `parent.postMessage({opengenieFrame:k,height:h},"*")}` +
    `addEventListener("load",s);if(window.ResizeObserver){new ResizeObserver(s).observe(document.documentElement)}` +
    `setTimeout(s,50);setTimeout(s,400)})()</script>`;
  return `<!doctype html><html><head><meta charset="utf-8"><base target="_blank">` +
    `<style>html,body{margin:0}body{padding:8px;font:13px/1.45 system-ui,-apple-system,sans-serif;color:#1b1b1b;background:#fff}` +
    `table{border-collapse:collapse}th,td{padding:4px 8px;border:1px solid #ddd;text-align:left}</style></head>` +
    `<body>${html}${report}</body></html>`;
}

/** The height a frame reported, or null when the message is not ours or is not a sane number. */
export function frameHeight(data: unknown, id: string): number | null {
  if (!data || typeof data !== "object") return null;
  const d = data as { opengenieFrame?: unknown; height?: unknown };
  if (d.opengenieFrame !== id) return null;
  if (typeof d.height !== "number" || !Number.isFinite(d.height)) return null;
  return Math.max(MIN_FRAME, Math.min(MAX_FRAME, Math.ceil(d.height)));
}
