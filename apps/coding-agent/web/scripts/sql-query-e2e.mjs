async function screenshot(name) {
  await page.evaluate(() => document.fonts.ready);
  await expect(page.locator('.sql-loading')).toHaveCount(0);
  if (await page.locator('.sql-editor').count()) await expect(page.locator('.sql-editor .editor-host')).toHaveAttribute('data-status','ready');
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),{timeout:5000}).toBe(true);
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const path = resolve(shots, `${name}.png`);
  if(captureScreenshots)await page.screenshot({ path, fullPage: true, animations: 'disabled' });
  else expect(existsSync(path),`Previously inspected screenshot missing: ${path}`).toBe(true);
  screenshots.push(path);
}
async function sql(text) {
  const editor = page.locator('.sql-source-pane .cm-content');
  await editor.waitFor(); await editor.fill(text);
  await expect.poll(() => editor.innerText()).toBe(text);
  await page.waitForTimeout(250);
}
